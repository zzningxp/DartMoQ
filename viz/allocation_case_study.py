"""Expert bit allocation case study visualization.

This module reads the JSON files generated by `logs/allocation_case_study.py`
and creates intuitive visualizations comparing the three bit allocation
strategies:

    - Expert-Fixed: Each expert uses the same fixed bit schedule
    - Global-Fixed: Globally-ranked, but still using fixed number of high bits
    - Global-BPW: Global dynamic programming allocation under bpw constraint

Usage
-----
    python -m viz.allocation_case_study                    # all models (PNG)
    python -m viz.allocation_case_study --model dsv1      # one model (PNG)
    python -m viz.allocation_case_study --pdf             # save as PDF
    python -m viz.allocation_case_study --svg             # save as SVG
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import ListedColormap
from matplotlib.patches import Rectangle

# Make sibling modules importable when run as a script.
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

OUT_ROOT = "plot/allocation_case_study"
DATA_ROOT = "logs/allocation_case_study"

